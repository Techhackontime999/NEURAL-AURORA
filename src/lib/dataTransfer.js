function csvEscape(value) {
  if (value === null || value === undefined) return ''
  const str = typeof value === 'object' ? JSON.stringify(value) : String(value)
  return /[",\n\r]/.test(str) ? `"${str.replace(/"/g, '""')}"` : str
}

/** Serialise an array of row objects to CSV text (union of all columns). */
export function rowsToCsv(rows) {
  if (!rows || !rows.length) return ''
  const headers = []
  for (const row of rows) {
    for (const key of Object.keys(row)) {
      if (!headers.includes(key)) headers.push(key)
    }
  }
  const lines = [headers.join(',')]
  for (const row of rows) {
    lines.push(headers.map((h) => csvEscape(row[h])).join(','))
  }
  return lines.join('\r\n')
}

function coerceCsvValue(raw) {
  const str = typeof raw === 'string' ? raw : raw == null ? '' : String(raw)
  const trimmed = str.trim()
  if (trimmed === '') return ''
  if (trimmed === 'null') return null
  if (trimmed === 'true') return true
  if (trimmed === 'false') return false
  const looksStructured =
    (trimmed.startsWith('[') && trimmed.endsWith(']')) ||
    (trimmed.startsWith('{') && trimmed.endsWith('}'))
  if (looksStructured) {
    try {
      return JSON.parse(trimmed)
    } catch {
      return str
    }
  }
  return str
}

/** Parse RFC-4180 CSV text into row objects. */
export function csvToRows(text) {
  const input = String(text).replace(/^\uFEFF/, '')
  const records = []
  let record = []
  let field = ''
  let inQuotes = false

  for (let i = 0; i < input.length; i += 1) {
    const ch = input[i]
    if (inQuotes) {
      if (ch === '"') {
        if (input[i + 1] === '"') {
          field += '"'
          i += 1
        } else {
          inQuotes = false
        }
      } else {
        field += ch
      }
      continue
    }
    if (ch === '"') {
      inQuotes = true
    } else if (ch === ',') {
      record.push(field)
      field = ''
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && input[i + 1] === '\n') i += 1
      record.push(field)
      field = ''
      if (record.length > 1 || record[0] !== '') records.push(record)
      record = []
    } else {
      field += ch
    }
  }
  if (field !== '' || record.length) {
    record.push(field)
    if (record.length > 1 || record[0] !== '') records.push(record)
  }
  if (!records.length) return []

  const headers = records[0].map((h) => h.trim())
  return records.slice(1).map((cells) => {
    const row = {}
    headers.forEach((header, index) => {
      row[header] = coerceCsvValue(cells[index] ?? '')
    })
    return row
  })
}

