export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

function downloadCsv(rows, filename) {
  const csv = rowsToCsv(rows)
  if (!csv) return false
  downloadBlob(new Blob([csv], { type: 'text/csv;charset=utf-8;' }), filename)
  return true
}

/** Download a full JSON backup. `tables` = { table: rows[] }. */
export function exportJsonBackup(tables) {
  const payload = {
    app: 'neural-aurora',
    kind: 'data-backup',
    version: 1,
    exported_at: new Date().toISOString(),
    tables,
  }
  downloadBlob(
    new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' }),
    backupFilename('json')
  )
}

/**
 * Download CSV. A single table becomes one file; multiple tables become one
 * file per table (browsers queue the downloads).
 */
export async function exportCsvBackup(tables) {
  const names = Object.keys(tables)
  if (names.length === 1) {
    return downloadCsv(tables[names[0]], `${names[0]}.csv`)
  }
  const stamp = new Date().toISOString().slice(0, 10)
  for (const name of names) {
    downloadCsv(tables[name], `neural-aurora-${name}-${stamp}.csv`)
    await new Promise((resolve) => setTimeout(resolve, 250))
  }
  return true
}

