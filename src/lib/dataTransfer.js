/** Tables that can be written back by the admin (browser safe). */
export const IMPORTABLE_TABLES = DATA_TABLES.filter((t) => t.importable)

/** Ids / audit columns regenerated by the database on insert. */
const ALWAYS_STRIP = ['id', 'created_at', 'updated_at']

const PAGE_SIZE = 1000

function tableConfig(table) {
  return DATA_TABLES.find((t) => t.table === table)
}

export function tableLabel(table) {
  return tableConfig(table)?.label || table
}

export function backupFilename(format) {
  const stamp = new Date().toISOString().slice(0, 10)
  return `neural-aurora-backup-${stamp}.${format}`
}

