/**
 * Parse an uploaded file into `{ tables: { table: rows[] } }`.
 * - JSON: our backup format, or a bare array (use `fallbackTable`).
 * - CSV : one table per file (use `fallbackTable`).
 */
export function parseImportFile(text, filename = '', fallbackTable = null) {
  const isJson = filename.toLowerCase().endsWith('.json') || text.trimStart().startsWith('{') || text.trimStart().startsWith('[')
  if (isJson) {
    const parsed = JSON.parse(text)
    if (Array.isArray(parsed)) {
      if (!fallbackTable) throw new Error('This file has no table name — pick the target table first.')
      return { tables: { [fallbackTable]: parsed } }
    }
    if (parsed.tables && typeof parsed.tables === 'object') {
      return { tables: parsed.tables }
    }
    if (Array.isArray(parsed.rows)) {
      const table = parsed.table || fallbackTable
      if (!table) throw new Error('This file has no table name — pick the target table first.')
      return { tables: { [table]: parsed.rows } }
    }
    throw new Error('Unrecognised JSON backup file.')
  }
  if (!fallbackTable) throw new Error('Pick the target table before importing a CSV file.')
  return { tables: { [fallbackTable]: csvToRows(text) } }
}

function prepareRow(row, config) {
  const out = {}
  for (const [key, value] of Object.entries(row || {})) {
    if (ALWAYS_STRIP.includes(key)) continue
    if (config.strip?.includes(key)) continue
    if (value === undefined) continue
    out[key] = value
  }
  return out
}

async function importSingleRowTable(table, rows) {
  const row = rows[0]
  if (!row) return { count: 0 }
  const payload = { ...row, id: 1 }
  const { error } = await supabase.from(table).upsert([payload], { onConflict: 'id' })
  if (error) throw new Error(error.message)
  return { count: 1 }
}

/**
 * Write imported rows back to Supabase.
 *
 * @param {object} tables  { table: rows[] }
 * @param {'merge'|'replace'} mode
 *   merge   – upsert on the stable unique key (falls back to insert)
 *   replace – delete all rows first, then insert (destructive)
 * @param {function} onProgress called with the running results array
 * @returns {Promise<Array<{table,label,status,count,message}>>}
 */
export async function importTables(tables, mode, onProgress) {
  const orderOf = (name) => {
    const index = DATA_TABLES.findIndex((t) => t.table === name)
    return index === -1 ? DATA_TABLES.length : index
  }
  // Parents before children regardless of the order they appear in the file.
  const names = Object.keys(tables).sort((a, b) => orderOf(a) - orderOf(b))
  const configs = names.map(tableConfig)

  const results = []
  const cleared = new Set()

  // Replace mode: wipe children before parents (reverse of DATA_TABLES order).
  if (mode === 'replace') {
    for (let i = names.length - 1; i >= 0; i -= 1) {
      const config = configs[i]
      if (!config?.importable || config.singleRow) continue
      const { error } = await supabase.from(config.table).delete().not('id', 'is', null)
      if (error) {
        results.push({
          table: config.table,
          label: config.label,
          status: 'error',
          count: 0,
          message: `Could not clear table: ${error.message}`,
        })
      } else {
        cleared.add(config.table)
      }
      onProgress?.([...results])
    }
  }

  for (let i = 0; i < names.length; i += 1) {
    const name = names[i]
    const config = configs[i]
    const rawRows = tables[name]
    const label = config?.label || name

    if (!config) {
      results.push({ table: name, label, status: 'skipped', count: 0, message: 'Unknown table — skipped' })
      onProgress?.([...results])
      continue
    }
    if (!config.importable) {
      results.push({ table: name, label, status: 'skipped', count: 0, message: 'Read-only (server-managed) — skipped' })
      onProgress?.([...results])
      continue
    }
    if (mode === 'replace' && !config.singleRow && !cleared.has(name)) {
      const existing = results.find((r) => r.table === name)
      if (existing) continue // already reported as a failed wipe
    }

    const rows = (Array.isArray(rawRows) ? rawRows : [])
      .map((row) => prepareRow(row, config))
      .filter((row) => Object.keys(row).length > 0)

    if (!rows.length) {
      results.push({ table: name, label, status: 'ok', count: 0, message: 'No rows in file' })
      onProgress?.([...results])
      continue
    }

    try {
      if (config.singleRow) {
        const { count } = await importSingleRowTable(name, rows)
        results.push({ table: name, label, status: 'ok', count })
      } else {
        const hasKey = config.uniqueKey && rows.some((r) => r[config.uniqueKey] != null && r[config.uniqueKey] !== '')
        // Guard against duplicate keys inside one file (ON CONFLICT can't
        // update the same row twice in a single statement).
        let payload = rows
        if (hasKey) {
          const byKey = new Map()
          for (const row of rows) byKey.set(row[config.uniqueKey], row)
          payload = [...byKey.values()]
        }
        const { error } = hasKey
          ? await supabase.from(name).upsert(payload, { onConflict: config.uniqueKey })
          : await supabase.from(name).insert(payload)
        if (error) throw new Error(error.message)
        results.push({ table: name, label, status: 'ok', count: payload.length })
      }
    } catch (err) {
      results.push({ table: name, label, status: 'error', count: 0, message: err.message })
    }
    onProgress?.([...results])
  }
  return results
}

/** Total rows across a `{ table: rows[] }` map. */
export function countDumpRows(tables) {
  return Object.values(tables || {}).reduce((sum, rows) => sum + (Array.isArray(rows) ? rows.length : 0), 0)
}
