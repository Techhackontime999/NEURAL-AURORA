/** Read every row of a table, paging past Supabase's 1000-row limit. */
export async function fetchAllRows(table) {
  const rows = []
  let from = 0
  for (;;) {
    const { data, error } = await supabase
      .from(table)
      .select('*')
      .order('id', { ascending: true })
      .range(from, from + PAGE_SIZE - 1)
    if (error) throw new Error(`${tableLabel(table)}: ${error.message}`)
    rows.push(...(data || []))
    if (!data || data.length < PAGE_SIZE) break
    from += PAGE_SIZE
  }
  return rows
}

/** Row counts for every known table (best effort, never throws). */
export async function fetchTableCounts() {
  const entries = await Promise.all(
    DATA_TABLES.map(async ({ table }) => {
      const { count, error } = await supabase
        .from(table)
        .select('*', { count: 'exact', head: true })
      return [table, error ? null : count ?? 0]
    })
  )
  return Object.fromEntries(entries)
}

/** Collect a dump of the given tables: { table: rows[] }. */
export async function collectData(tables, onProgress) {
  const dump = {}
  for (const table of tables) {
    onProgress?.(table)
    dump[table] = await fetchAllRows(table)
  }
  return dump
}

